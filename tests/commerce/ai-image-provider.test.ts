import { readFileSync } from 'node:fs';
import { describe, expect, it, vi, afterEach } from 'vitest';
import { OpenAIImageProvider } from '@/lib/ai/openai-image-provider';
import { generateDurableArtwork } from '@/lib/ai/generate-artwork';
import { getImageProvider } from '@/lib/ai/image-provider';

const source = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
const output = readFileSync('public/designs/seasonal-edit/haunted-household.png');
const response = () => new Response(JSON.stringify({ data: [{ b64_json: output.toString('base64') }] }), { headers: { 'x-request-id': 'req-fake' } });
afterEach(() => { vi.unstubAllEnvs(); vi.useRealTimers(); vi.restoreAllMocks(); });

describe('GPT Image commerce provider', () => {
  it('sends source image A as an actual image edit input and persists generated bytes before returning a preview', async () => {
    const transport = vi.fn<typeof fetch>().mockResolvedValue(response());
    const persist = vi.fn().mockResolvedValue({ productionAssetUrl: 'https://assets.example.test/saved.png', storagePath: 'production/design-a/r1.png', checksum: 'checksum' });
    const result = await generateDurableArtwork({ imageUrl: source, promptTemplate: 'Halloween pet portrait', workflow: 'photo-edit' }, { designId: 'design-a', revision: 1 }, { provider: new OpenAIImageProvider('fake-key', transport), persist });
    expect(transport.mock.calls[0][0]).toBe('https://api.openai.com/v1/images/edits');
    const payload = JSON.parse(transport.mock.calls[0][1]!.body as string);
    expect(payload).toMatchObject({ model: 'gpt-image-2.5-sunburst', images: [{ image_url: source }], output_format: 'png', background: 'transparent', quality: 'high' });
    expect(payload).not.toHaveProperty('style');
    expect(payload).not.toHaveProperty('response_format');
    expect(persist).toHaveBeenCalledWith({ designId: 'design-a', revision: 1, mimeType: 'image/png', bytes: output });
    expect(result.productionAssetUrl).toBe('https://assets.example.test/saved.png');
    expect(result).not.toHaveProperty('imageUrl');
  });
  it('uses Flare without any image inputs for original concepts', async () => {
    const transport = vi.fn<typeof fetch>().mockResolvedValue(response());
    await new OpenAIImageProvider('fake-key', transport).generateDesign({ promptTemplate: 'Original pumpkin patch graphic', workflow: 'text-generation' });
    expect(transport.mock.calls[0][0]).toBe('https://api.openai.com/v1/images/generations');
    expect(JSON.parse(transport.mock.calls[0][1]!.body as string)).toMatchObject({ model: 'gpt-image-2.5-flare' });
    expect(JSON.parse(transport.mock.calls[0][1]!.body as string)).not.toHaveProperty('images');
  });
  it('rejects missing photos, arbitrary remote URLs, unsupported images and retired models before calling OpenAI', async () => {
    const transport = vi.fn<typeof fetch>();
    const provider = new OpenAIImageProvider('fake-key', transport);
    for (const imageUrl of [undefined, 'http://localhost/private', 'https://untrusted.example/photo.png', 'data:image/svg+xml;base64,AAAA', 'data:image/png;base64,AAAA']) {
      await expect(provider.generateDesign({ imageUrl, promptTemplate: 'Portrait' })).rejects.toThrow();
    }
    vi.stubEnv('OPENAI_IMAGE_EDIT_MODEL', 'dall-e-3');
    await expect(provider.generateDesign({ imageUrl: source, promptTemplate: 'Portrait' })).rejects.toMatchObject({ code: 'INVALID_MODEL' });
    expect(transport).not.toHaveBeenCalled();
  });
  it('allows model configuration and keeps upstream private errors out of customer messages', async () => {
    vi.stubEnv('OPENAI_IMAGE_EDIT_MODEL', 'gpt-image-2.5-sunburst-2026-09-08');
    const transport = vi.fn<typeof fetch>().mockResolvedValue(new Response(JSON.stringify({ error: { message: 'customer image and secret-key' } }), { status: 500 }));
    await expect(new OpenAIImageProvider('fake-key', transport).generateDesign({ imageUrl: source, promptTemplate: 'Portrait' })).rejects.toMatchObject({ code: 'GENERATION_FAILED', message: 'Image generation is busy. Please try again shortly.' });
    expect(transport).toHaveBeenCalledTimes(1);
  });
  it('retries a rate limit at most once', async () => {
    vi.useFakeTimers();
    const transport = vi.fn<typeof fetch>().mockResolvedValue(new Response('', { status: 429 }));
    const promise = new OpenAIImageProvider('fake-key', transport).generateDesign({ imageUrl: source, promptTemplate: 'Portrait' });
    const assertion = expect(promise).rejects.toMatchObject({ code: 'GENERATION_FAILED' });
    await vi.advanceTimersByTimeAsync(1000);
    await assertion;
    expect(transport).toHaveBeenCalledTimes(2);
  });
  it('aborts a timed out request without repeating a possibly charged generation', async () => {
    vi.useFakeTimers();
    const transport = vi.fn<typeof fetch>().mockImplementation((_url, init) => new Promise((_resolve, reject) => init!.signal!.addEventListener('abort', () => reject(new Error('aborted')))));
    const promise = new OpenAIImageProvider('fake-key', transport).generateDesign({ imageUrl: source, promptTemplate: 'Portrait' });
    const assertion = expect(promise).rejects.toMatchObject({ code: 'GENERATION_TIMEOUT' });
    await vi.advanceTimersByTimeAsync(90_000);
    await assertion;
    expect(transport).toHaveBeenCalledTimes(1);
  });
  it('does not retry exhausted quota or return upstream private details', async () => {
    const transport = vi.fn<typeof fetch>().mockResolvedValue(new Response(JSON.stringify({ error: { code: 'insufficient_quota', message: 'private account details' } }), { status: 429 }));
    await expect(new OpenAIImageProvider('fake-key', transport).generateDesign({ imageUrl: source, promptTemplate: 'Portrait' })).rejects.toMatchObject({ code: 'PROVIDER_UNAVAILABLE', status: 503 });
    expect(transport).toHaveBeenCalledTimes(1);
  });
  it('does not return a completed preview when persistence fails', async () => {
    const persist = vi.fn().mockRejectedValue(new Error('storage unavailable'));
    await expect(generateDurableArtwork({ imageUrl: source, promptTemplate: 'Portrait' }, { designId: 'design-a', revision: 1 }, { provider: new OpenAIImageProvider('fake-key', vi.fn<typeof fetch>().mockResolvedValue(response())), persist })).rejects.toThrow('storage unavailable');
  });
  it('cannot silently serve mock images in production', async () => {
    vi.stubEnv('NODE_ENV', 'production'); vi.stubEnv('AI_PROVIDER', 'mock');
    await expect(getImageProvider()).rejects.toMatchObject({ code: 'PROVIDER_UNAVAILABLE' });
  });
});
